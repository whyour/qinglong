function shellFunction(name) {
  const source = fs.readFileSync(path.resolve('shell/update.sh'), 'utf8');
  const start = source.indexOf(`${name}() {`);
  assert.ok(start >= 0);
  return source.slice(start, source.indexOf('\n}', start) + 2);
}

function updateFixture(t) {
  const root = temporary(t);
  const template = path.join(root, 'template');
  for (const dir of ['template', 'repo', 'scripts', 'lists'])
    fs.mkdirSync(path.join(root, dir));
  for (const file of ['keep.js', 'keep.py', 'omit.js', 'other.txt', 'dep.js'])
    fs.writeFileSync(path.join(template, file), file);
  for (const file of ['notify.js', 'notify.py', 'crontab'])
    fs.writeFileSync(path.join(root, file), '');
  const helpers = [
    'update_repo',
    'diff_scripts',
    'gen_list_repo',
    'get_uniq_path',
  ]
    .map(shellFunction)
    .join('\n');
  return {
    root,
    run: (extensions, dependence = 'dep') => {
      const doc = {
        id: 1,
        type: 'public-repo',
        alias: 'owner_repo',
        url: 'https://example.invalid/owner/repo.git',
        whitelist: 'keep',
        blacklist: 'omit',
        dependences: dependence,
        extensions,
        autoAddCron: false,
        autoDelCron: false,
      };
      const code = `dir_repo="$QA_ROOT/repo"; dir_scripts="$QA_ROOT/scripts"; dir_list_tmp="$QA_ROOT/lists"
file_notify_js="$QA_ROOT/notify.js"; file_notify_py="$QA_ROOT/notify.py"; list_crontab_user="$QA_ROOT/crontab"
cmd_task=task; file_extensions='js py'
${helpers}
t() { :; }; make_dir() { mkdir -p "$1"; }; diff_cron() { :; }
git_clone_scripts() { mkdir -p "$2"; cp "$QA_ROOT/template/"* "$2/"; exit_status=0; }
ql() { get_uniq_path "$2" "$6"; update_repo "${'${@:2}'}"; }
${formatCommand(doc)}`;
      execFileSync('/bin/bash', ['-c', code], {
        env: { ...process.env, QA_ROOT: root },
        encoding: 'utf8',
        timeout: 5000,
      });
      return path.join(root, 'scripts', 'owner_repo');
    },
  };
}

test('real repository update supports extension separators, filtering and dependency copies', (t) => {
  for (const extension of ['js|py', 'js py', 'js\tpy', 'js\npy', '']) {
    const f = updateFixture(t);
    const scripts = f.run(extension);
    assert.deepEqual(fs.readdirSync(scripts).sort(), [
      'dep.js',
      'keep.js',
      'keep.py',
      'notify.js',
      'notify.py',
    ]);
    assert.deepEqual(
      fs
        .readFileSync(
          path.join(f.root, 'lists', 'owner_repo_scripts.list'),
          'utf8',
        )
        .trim()
        .split('\n')
        .sort(),
      ['owner_repo/keep.js', 'owner_repo/keep.py'],
    );
  }
});

test('real repository update never evaluates extension input, including dependency discovery', (t) => {
  const f = updateFixture(t);
  const marker = path.join(f.root, 'executed');
  const payloads = [
    'js|$(touch${IFS}' + marker + ')',
    'js|`touch${IFS}' + marker + '`',
    'js|py";touch${IFS}' + marker + ';#',
    'js|$(touch${IFS}' + marker + ')\npy',
  ];
  for (const payload of payloads) {
    const scripts = f.run(payload);
    assert.equal(fs.existsSync(marker), false, payload);
    assert.equal(
      fs.readFileSync(path.join(scripts, 'keep.js'), 'utf8'),
      'keep.js',
    );
    assert.equal(
      fs.readFileSync(path.join(scripts, 'dep.js'), 'utf8'),
      'dep.js',
    );
  }
});

test('force deletion supports historical nested aliases while preserving outside targets', async (t) => {
  const root = temporary(t);
  const config = {
    scriptPath: path.join(root, 'scripts'),
    repoPath: path.join(root, 'repo'),
  };
  const alias = 'owner_repo_feature/foo';
  for (const dir of [config.scriptPath, config.repoPath]) {
    fs.mkdirSync(path.join(dir, alias), { recursive: true });
    fs.writeFileSync(path.join(dir, alias, 'file'), 'fixture');
  }
  const outside = path.join(root, 'outside');
  fs.mkdirSync(outside);
  fs.writeFileSync(path.join(outside, 'file'), 'keep');
  let destroyed = 0;
  const doc = { id: 1, alias, get: () => doc };
  const Subscription = load(path.resolve('back/services/subscription.ts'), {
    '../config': config,
    '../data/subscription': {
      SubscriptionModel: {
        findAll: async () => [doc],
        destroy: async () => destroyed++,
      },
    },
    '../data/cron': { CrontabModel: { findAll: async () => [] } },
    '../config/util': {
      rmPath: (p) => fs.promises.rm(p, { recursive: true, force: true }),
    },
    '../config/const': {},
    '../shared/i18n': { t: (x) => x, tf: (x) => x },
    '../shared/pLimit': {},
    './schedule': {},
    './sock': {},
    './sshKey': {},
    './cron': {},
  }).default;
  const service = new Subscription({}, {}, {}, {}, {});
  service.handleTask = async () => {};
  service.setSshConfig = async () => {};
  await service.remove([1], { force: true });
  assert.equal(destroyed, 1);
  for (const dir of [config.scriptPath, config.repoPath])
    assert.equal(fs.existsSync(path.join(dir, alias)), false);
  fs.symlinkSync(outside, path.join(config.scriptPath, 'escape'));
  doc.alias = 'escape/file';
  await assert.rejects(
    service.remove([1], { force: true }),
    /Invalid subscription path/,
  );
  assert.equal(destroyed, 1);
  assert.equal(fs.readFileSync(path.join(outside, 'file'), 'utf8'), 'keep');
  assert.equal(paths.getSubscriptionSshAlias('仓库-main'), '仓库-main');
});
