function temporary(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ql-sub-review-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  return root;
}

function privateSubscription(alias, id = 1) {
  return {
    id,
    type: 'private-repo',
    pull_type: 'ssh-key',
    alias,
    url: 'git@example.com:owner/repo.git',
    pull_option: { private_key: 'fixture-key' },
  };
}

function sshService(root, warnings = []) {
  const Ssh = load(path.resolve('back/services/sshKey.ts'), {
    typedi: { Service: () => (x) => x, Inject: () => () => {} },
    '../config': { sshdPath: root },
    '../config/util': {
      fileExist: async (p) => fs.existsSync(p),
      rmPath: (p) => fs.promises.rm(p, { recursive: true, force: true }),
    },
  }).default;
  return Object.assign(Object.create(Ssh.prototype), {
    sshPath: root,
    logger: { error() {}, warn: (...args) => warnings.push(args) },
  });
}

test('aliases generated by the frontend for valid branches remain accepted', () => {
  const text = fs.readFileSync(
    path.resolve('src/pages/subscription/modal.tsx'),
    'utf8',
  );
  const source = text.slice(
    text.indexOf('const formatAlias ='),
    text.indexOf('\n\n  const IntervalSelect'),
  );
  const js = ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2020 },
  }).outputText;
  const formatAlias = new Function(
    'repoUrlRegx',
    'fileUrlRegx',
    'type',
    js + '\nreturn formatAlias;',
  )(
    /([^\/\:]+\/[^\/]+)(?=\.git)/,
    /([^\/\:]+\/[^\/\.]+)\.[a-z]+/,
    'public-repo',
  );
  for (const branch of [
    'main',
    'release+hotfix',
    'feature/foo',
    'feature/foo/bar',
    'release@v2',
    'release#v2',
  ]) {
    const alias = formatAlias('https://example.com/owner/repo.git', branch);
    assert.equal(alias, `owner_repo_${branch}`);
    assert.doesNotThrow(() => paths.assertSubscriptionAlias(alias));
  }
});

test('nested aliases stay inside the root and cannot claim internal SSH names', (t) => {
  const root = temporary(t);
  const scripts = path.join(root, 'scripts');
  fs.mkdirSync(scripts);
  assert.equal(
    paths.resolveSubscriptionPath(scripts, 'owner_repo_feature/foo'),
    path.join(scripts, 'owner_repo_feature/foo'),
  );
  fs.symlinkSync(root, path.join(scripts, 'escape'));
  assert.throws(() => paths.resolveSubscriptionPath(scripts, 'escape/outside'));
  for (const alias of [
    '.',
    '..',
    '../outside',
    '/outside',
    'x/../outside',
    'x/./a',
    'x//a',
    'x/',
    'x\\a',
    'x\0a',
    'x\nHost *',
    'x y',
    '~global_secret',
    '~sub_' + 'a'.repeat(64),
  ]) {
    assert.throws(() => paths.assertSubscriptionAlias(alias), alias);
  }
  assert.throws(() => paths.assertSubscriptionAlias('a'.repeat(201)));
});

test('SSH URL, key and configuration use the same stable name for nested aliases', async (t) => {
  const root = temporary(t);
  const ssh = sshService(root);
  const docs = [
    privateSubscription('owner_repo_release+hotfix'),
    privateSubscription('owner_repo_feature/foo', 2),
    privateSubscription('owner_repo_feature_foo', 3),
    privateSubscription('owner_repo.config', 4),
  ];
  const snapshot = structuredClone(docs);
  await ssh.setSshConfig(docs);
  assert.deepEqual(docs, snapshot);
  const mapped = paths.getSubscriptionSshAlias(docs[1].alias);
  assert.match(mapped, /^~sub_[a-f0-9]{64}$/);
  assert.notEqual(mapped, paths.getSubscriptionSshAlias(docs[2].alias));
  assert.equal(paths.getSubscriptionSshAlias(docs[0].alias), docs[0].alias);
  for (const doc of docs) {
    const name = paths.getSubscriptionSshAlias(doc.alias);
    const key = path.join(root, name);
    const config = path.join(root, `${name}.config`);
    assert.equal(fs.readFileSync(key, 'utf8').trim(), 'fixture-key');
    assert.equal(fs.statSync(key).mode & 0o777, 0o400);
    assert.equal(fs.statSync(config).mode & 0o777, 0o600);
    assert.match(
      fs.readFileSync(config, 'utf8'),
      new RegExp('^Host ' + name.replace(/[.+]/g, '\\$&') + '\n'),
    );
    assert.equal(formatUrl(doc).url, `git@${name}:owner/repo.git`);
    const parsed = execFileSync('ssh', ['-G', '-F', config, name], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    assert.match(parsed, /^hostname example\.com$/m);
    assert.ok(parsed.includes(`identityfile ${key}\n`));
  }
  await ssh.removeSSHKey(docs[1].alias, 'example.com');
  assert.equal(fs.existsSync(path.join(root, mapped)), false);
  assert.equal(fs.existsSync(path.join(root, `${mapped}.config`)), false);
  await ssh.addSSHKey('replacement', docs[1].alias, 'example.com');
  assert.equal(
    fs.readFileSync(path.join(root, mapped), 'utf8').trim(),
    'replacement',
  );
});

test('startup retains historical aliases and isolates bad rows and asynchronous scheduling failures', async (t) => {
  const root = temporary(t);
  const warnings = [];
  const ssh = sshService(root, warnings);
  const docs = [
    privateSubscription('owner_repo_release+hotfix', 1),
    privateSubscription('owner_repo_feature/foo', 2),
    privateSubscription('../outside', 3),
    {
      id: 4,
      type: 'public-repo',
      alias: 'failed-job',
      url: 'https://example.com/repo.git',
    },
    {
      id: 5,
      type: 'public-repo',
      alias: 'healthy-job',
      url: 'https://example.com/repo.git',
    },
  ];
  const registered = [];
  const types = Object.fromEntries(
    ['system', 'schedule', 'subscription', 'ssh'].map((key) => [key, class {}]),
  );
  const services = new Map([
    [types.system, { getSystemConfig: async () => ({}) }],
    [
      types.schedule,
      { cancelIntervalTask: async () => {}, createIntervalTask: () => {} },
    ],
    [types.ssh, ssh],
    [
      types.subscription,
      {
        setSshConfig: () => ssh.setSshConfig(docs),
        list: async () => docs.map((doc) => ({ ...doc, get: () => doc })),
        handleTask: async (doc) => {
          if (doc.id === 4) throw new Error('unavailable scheduler');
          registered.push(doc.id);
        },
      },
    ],
  ]);
  const initTask = load(path.resolve('back/loaders/initTask.ts'), {
    '../config': { rootPath: root },
    '../config/util': { fileExist: async () => false },
    '../shared/i18n': { t: (x) => x },
    './logger': { warn: (...args) => warnings.push(args) },
    '../services/system': types.system,
    '../services/schedule': types.schedule,
    '../services/subscription': types.subscription,
    '../services/sshKey': types.ssh,
    typedi: { Container: { get: (key) => services.get(key) } },
  }).default;
  await initTask();
  assert.deepEqual(registered, [1, 2, 5]);
  assert.equal(warnings.length, 3);
  assert.equal(
    fs.existsSync(path.join(root, 'owner_repo_release+hotfix.config')),
    true,
  );
});

